import assert from 'assert';
import { createUser } from '../controllers/authController.js';
import { User } from '../models/User.js';
import { AuditLog } from '../models/AuditLog.js';
import { USER_ROLES } from '../config/constants.js';

async function runTests() {
  console.log('--- BẮT ĐẦU KIỂM THỬ UC-10.1: CREATE USER ---');

  // Mock database in-memory store
  const mockDb = [
    {
      _id: '67a000000000000000000001',
      code: 'AD001',
      email: 'admin@ruo.edu.vn',
      full_name: 'Quản Trị Viên',
      role: USER_ROLES.ADMIN
    },
    {
      _id: '67a000000000000000000002',
      code: 'GV001',
      email: 'lecturer@ruo.edu.vn',
      full_name: 'Giảng Viên Mẫu',
      role: USER_ROLES.LECTURER
    }
  ];

  // Mock AuditLog
  AuditLog.logAction = async () => true;

  // Mock User.findOne
  User.findOne = async (query) => {
    if (query.code) {
      return mockDb.find(u => u.code.toUpperCase() === query.code.toUpperCase()) || null;
    }
    if (query.email) {
      return mockDb.find(u => u.email.toLowerCase() === query.email.toLowerCase()) || null;
    }
    return null;
  };

  // Mock User.create
  User.create = async (doc) => {
    const created = {
      _id: `67a00000000000000000000${mockDb.length + 1}`,
      ...doc
    };
    mockDb.push(created);
    return created;
  };

  // TEST 1: Tạo tài khoản thành công với mật khẩu tự động ngẫu nhiên
  console.log('▶ Test 1: Tạo tài khoản thành công và tự sinh mật khẩu ngẫu nhiên');
  {
    let statusCode = 200;
    let jsonResult = null;
    const req = {
      user: { _id: '67a000000000000000000001', code: 'AD001', full_name: 'Admin' },
      body: {
        code: 'KT005',
        full_name: 'Kỹ Thuật Viên Mới',
        email: 'kt005@ruo.edu.vn',
        role: USER_ROLES.TECHNICIAN,
        department: 'Tổ Kỹ Thuật Bảo Trì',
        phone: '0988112233'
      },
      ip: '127.0.0.1'
    };
    const res = {
      status: (code) => { statusCode = code; return res; },
      json: (data) => { jsonResult = data; return res; }
    };

    await createUser(req, res);

    assert.strictEqual(statusCode, 201, 'Status phải là 201 Created');
    assert.strictEqual(jsonResult.success, true);
    assert.strictEqual(jsonResult.user.code, 'KT005');
    assert.strictEqual(jsonResult.user.role, USER_ROLES.TECHNICIAN);
    assert.strictEqual(jsonResult.user.isAutoGenerated, true, 'isAutoGenerated phải là true');
    assert.strictEqual(jsonResult.user.force_change_pw, true, 'Mật khẩu tự sinh phải force_change_pw');
    assert.ok(jsonResult.user.tempPassword, 'Phải có tempPassword trả về cho Admin');
    assert.match(jsonResult.user.tempPassword, /^Ruo@\d{6}$/, 'Mật khẩu ngẫu nhiên phải có dạng Ruo@xxxxxx');
    console.log(`  ✔ Test 1 ĐẠT: Tài khoản tạo thành công với mật khẩu tự sinh [${jsonResult.user.tempPassword}].`);
  }

  // TEST 2: Chặn trùng mã nhân viên / CB (Unique Code)
  console.log('▶ Test 2: Chặn tạo tài khoản trùng Mã NV (Unique code constraint)');
  {
    let statusCode = 200;
    let jsonResult = null;
    const req = {
      user: { _id: '67a000000000000000000001', code: 'AD001', full_name: 'Admin' },
      body: {
        code: 'GV001', // Đã tồn tại trong mockDb
        full_name: 'Giảng Viên Trùng Mã',
        email: 'gv_trung_ma@ruo.edu.vn',
        role: USER_ROLES.LECTURER
      }
    };
    const res = {
      status: (code) => { statusCode = code; return res; },
      json: (data) => { jsonResult = data; return res; }
    };

    await createUser(req, res);

    assert.strictEqual(statusCode, 409, 'Phải trả về 409 Conflict');
    assert.strictEqual(jsonResult.success, false);
    assert.strictEqual(jsonResult.duplicateField, 'code', 'duplicateField phải là code');
    assert.match(jsonResult.message, /GV001/);
    console.log('  ✔ Test 2 ĐẠT: Bắt lỗi trùng mã NV chính xác.');
  }

  // TEST 3: Chặn trùng Email nhà trường (Unique Email)
  console.log('▶ Test 3: Chặn tạo tài khoản trùng Email (Unique email constraint)');
  {
    let statusCode = 200;
    let jsonResult = null;
    const req = {
      user: { _id: '67a000000000000000000001', code: 'AD001', full_name: 'Admin' },
      body: {
        code: 'GV999',
        full_name: 'Giảng Viên Trùng Email',
        email: 'admin@ruo.edu.vn', // Email đã tồn tại
        role: USER_ROLES.LECTURER
      }
    };
    const res = {
      status: (code) => { statusCode = code; return res; },
      json: (data) => { jsonResult = data; return res; }
    };

    await createUser(req, res);

    assert.strictEqual(statusCode, 409, 'Phải trả về 409 Conflict');
    assert.strictEqual(jsonResult.success, false);
    assert.strictEqual(jsonResult.duplicateField, 'email', 'duplicateField phải là email');
    assert.match(jsonResult.message, /admin@ruo\.edu\.vn/);
    console.log('  ✔ Test 3 ĐẠT: Bắt lỗi trùng email chính xác.');
  }

  // TEST 4: Tạo tài khoản với mật khẩu chỉ định đạt chuẩn bảo mật
  console.log('▶ Test 4: Tạo tài khoản với mật khẩu tùy chọn thỏa mãn chính sách bảo mật');
  {
    let statusCode = 200;
    let jsonResult = null;
    const req = {
      user: { _id: '67a000000000000000000001', code: 'AD001', full_name: 'Admin' },
      body: {
        code: 'QL002',
        full_name: 'Quản Lý CSVC Phó',
        email: 'manager.pho@ruo.edu.vn',
        role: USER_ROLES.FACILITY_MANAGER,
        password: 'Password@2026' // Mật khẩu hợp lệ
      }
    };
    const res = {
      status: (code) => { statusCode = code; return res; },
      json: (data) => { jsonResult = data; return res; }
    };

    await createUser(req, res);

    assert.strictEqual(statusCode, 201);
    assert.strictEqual(jsonResult.success, true);
    assert.strictEqual(jsonResult.user.isAutoGenerated, false);
    assert.strictEqual(jsonResult.user.force_change_pw, false);
    assert.strictEqual(jsonResult.user.tempPassword, 'Password@2026');
    console.log('  ✔ Test 4 ĐẠT: Chấp nhận mật khẩu chỉ định hợp lệ.');
  }

  // TEST 5: Bắt lỗi khi mật khẩu chỉ định yếu (không đạt chuẩn bảo mật)
  console.log('▶ Test 5: Bắt lỗi khi mật khẩu chỉ định không đạt chuẩn');
  {
    let statusCode = 200;
    let jsonResult = null;
    const req = {
      user: { _id: '67a000000000000000000001', code: 'AD001', full_name: 'Admin' },
      body: {
        code: 'GV888',
        full_name: 'Giảng Viên Mật Khẩu Yếu',
        email: 'gv888@ruo.edu.vn',
        role: USER_ROLES.LECTURER,
        password: '123' // Quá ngắn, không có chữ hoa, chữ thường, ký tự đặc biệt
      }
    };
    const res = {
      status: (code) => { statusCode = code; return res; },
      json: (data) => { jsonResult = data; return res; }
    };

    await createUser(req, res);

    assert.strictEqual(statusCode, 400);
    assert.strictEqual(jsonResult.success, false);
    assert.match(jsonResult.message, /bảo mật/i);
    console.log('  ✔ Test 5 ĐẠT: Từ chối mật khẩu không đạt chuẩn bảo mật.');
  }

  // TEST 6: Bắt lỗi thiếu trường bắt buộc
  console.log('▶ Test 6: Bắt lỗi khi thiếu trường bắt buộc (thiếu email)');
  {
    let statusCode = 200;
    let jsonResult = null;
    const req = {
      user: { _id: '67a000000000000000000001', code: 'AD001', full_name: 'Admin' },
      body: {
        code: 'GV777',
        full_name: 'Giảng Viên Thiếu Email'
        // Không có email
      }
    };
    const res = {
      status: (code) => { statusCode = code; return res; },
      json: (data) => { jsonResult = data; return res; }
    };

    await createUser(req, res);

    assert.strictEqual(statusCode, 400);
    assert.strictEqual(jsonResult.success, false);
    console.log('  ✔ Test 6 ĐẠT: Bắt lỗi thiếu trường bắt buộc.');
  }

  console.log('--- TOÀN BỘ 6/6 TEST CASES UC-10.1: CREATE USER ĐÃ VƯỢT QUA 100% ---');
}

runTests().catch(err => {
  console.error('Kiểm thử thất bại:', err);
  process.exit(1);
});
